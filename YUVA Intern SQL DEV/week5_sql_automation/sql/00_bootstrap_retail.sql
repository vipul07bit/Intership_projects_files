-- Week 5 automation lab bootstrap. PostgreSQL 14+
-- Uses the retail schema and table/column names documented in Weeks 1-2.
-- Safe for a fresh training database. On an existing DB, CREATE TABLE IF NOT EXISTS
-- will not replace your tables; review column compatibility before applying migrations.
CREATE SCHEMA IF NOT EXISTS retail;

CREATE TABLE IF NOT EXISTS retail.customers (
  customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(255) UNIQUE,
  phone VARCHAR(30),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS retail.categories (
  category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR(100) NOT NULL UNIQUE,
  description TEXT
);
CREATE TABLE IF NOT EXISTS retail.products (
  product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT REFERENCES retail.categories(category_id),
  sku VARCHAR(60) NOT NULL UNIQUE,
  product_name VARCHAR(200) NOT NULL,
  current_price NUMERIC(12,2) NOT NULL CHECK (current_price >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS retail.warehouses (
  warehouse_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  warehouse_name VARCHAR(150) NOT NULL,
  location_description VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS retail.inventory (
  product_id BIGINT NOT NULL REFERENCES retail.products(product_id),
  warehouse_id BIGINT NOT NULL REFERENCES retail.warehouses(warehouse_id),
  quantity_on_hand INTEGER NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (product_id, warehouse_id)
);
CREATE TABLE IF NOT EXISTS retail.orders (
  order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES retail.customers(customer_id),
  order_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  order_status VARCHAR(30) NOT NULL DEFAULT 'pending',
  shipping_address TEXT
);
CREATE TABLE IF NOT EXISTS retail.order_items (
  order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES retail.orders(order_id),
  product_id BIGINT NOT NULL REFERENCES retail.products(product_id),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0)
);
-- Additive operational attributes. Existing values are preserved.
ALTER TABLE retail.products ADD COLUMN IF NOT EXISTS unit_cost NUMERIC(12,2);
ALTER TABLE retail.inventory ADD COLUMN IF NOT EXISTS reorder_level INTEGER NOT NULL DEFAULT 10;
ALTER TABLE retail.inventory ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;
CREATE INDEX IF NOT EXISTS idx_orders_status_date ON retail.orders(order_status, order_date);
CREATE INDEX IF NOT EXISTS idx_order_items_product ON retail.order_items(product_id);
CREATE INDEX IF NOT EXISTS idx_inventory_warehouse_stock ON retail.inventory(warehouse_id, quantity_on_hand);
